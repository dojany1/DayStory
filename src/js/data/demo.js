/* Get today's story based on publish_date */
export function getTodayStory() {
  const today = new Date().toISOString().split('T')[0];
  return DEMO_STORIES.find(s => s.publish_date === today) || DEMO_STORIES[DEMO_STORIES.length - 1];
}

/* Get story by ID */
export function getStoryById(id) {
  return DEMO_STORIES.find(s => s.id === id);
}

/* Search stories */
export function searchStories(query) {
  const q = query.toLowerCase();
  return DEMO_STORIES.filter(s =>
    s.title.toLowerCase().includes(q) ||
    s.body.toLowerCase().includes(q) ||
    s.figure_name.toLowerCase().includes(q) ||
    s.country.toLowerCase().includes(q)
  );
}
